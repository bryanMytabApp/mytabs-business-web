# Deploy mytabs-client-web to keeptabs.app with Blue-Green Deployment
# This script builds and deploys the React application using versioned folders for zero-downtime deployments

param(
    [string]$Environment = "prod",
    [string]$S3Bucket = "mytabs-business-web-prod",
    [string]$CloudFrontDistributionId = "E1WB9UQAAX3TCW",
    [string]$AwsRegion = "us-east-1",
    [switch]$Rollback,
    [string]$RollbackVersion = "",
    # Skip the help API health check (use only when API is intentionally
    # offline or you've changed AllowedOrigins and need to deploy first).
    [switch]$SkipApiCheck
)

# Color output functions
function Write-Success { param([string]$Message) Write-Host "[OK] $Message" -ForegroundColor Green }
function Write-Error-Custom { param([string]$Message) Write-Host "[ERROR] $Message" -ForegroundColor Red }
function Write-Info { param([string]$Message) Write-Host "[INFO] $Message" -ForegroundColor Cyan }
function Write-Warning-Custom { param([string]$Message) Write-Host "[WARN] $Message" -ForegroundColor Yellow }
function Write-Step { param([string]$Num, [string]$Message) Write-Host "`n[Step $Num] $Message" -ForegroundColor Magenta }

# Version file path
$VersionFilePath = Join-Path $PSScriptRoot "client\src\config\version.js"
$VersionFile = Join-Path $PSScriptRoot ".deploy-versions.json"

# Function to get current version from version.js
function Get-CurrentAppVersion {
    if (Test-Path $VersionFilePath) {
        $content = Get-Content $VersionFilePath -Raw
        if ($content -match 'APP_VERSION\s*=\s*"(\d+)\.(\d+)\.(\d+)"') {
            return @{
                Major = [int]$Matches[1]
                Minor = [int]$Matches[2]
                Patch = [int]$Matches[3]
                Full = "$($Matches[1]).$($Matches[2]).$($Matches[3])"
            }
        }
    }
    return @{ Major = 1; Minor = 0; Patch = 0; Full = "1.0.0" }
}

# Function to increment and save version
function Update-AppVersion {
    $current = Get-CurrentAppVersion
    $newPatch = $current.Patch + 1
    $newVersion = "$($current.Major).$($current.Minor).$newPatch"
    
    $versionContent = @"
// Auto-generated by deploy script - DO NOT EDIT MANUALLY
export const APP_VERSION = "$newVersion";
"@
    
    Set-Content -Path $VersionFilePath -Value $versionContent -NoNewline
    return $newVersion
}

# Load or initialize version tracking
function Get-VersionHistory {
    # Always return a hashtable with the expected shape, regardless of what
    # the JSON file looks like. ConvertFrom-Json returns a PSCustomObject
    # that doesn't allow setting properties that don't already exist on it,
    # which is why earlier deploys threw on `$history.appVersion = ...`.
    $defaults = @{
        current    = ""
        previous   = ""
        history    = @()
        appVersion = "1.0.0"
    }
    if (Test-Path $VersionFile) {
        $raw = Get-Content $VersionFile | ConvertFrom-Json
        $merged = @{}
        foreach ($key in $defaults.Keys) { $merged[$key] = $defaults[$key] }
        # Copy across whatever the file already has, including extra fields
        # we didn't anticipate so we don't accidentally drop history.
        foreach ($prop in $raw.PSObject.Properties) {
            $merged[$prop.Name] = $prop.Value
        }
        # Make sure history is always an array (single-entry JSON deserializes
        # as a string in PowerShell).
        if ($null -eq $merged.history) {
            $merged.history = @()
        } elseif ($merged.history -isnot [System.Array]) {
            $merged.history = @($merged.history)
        }
        return $merged
    }
    return $defaults
}

function Save-VersionHistory {
    param($History)
    $History | ConvertTo-Json -Depth 10 | Set-Content $VersionFile
}

# ===============================================================================
# ROLLBACK MODE
# ===============================================================================
if ($Rollback) {
    Write-Host "`n[ROLLBACK] ROLLBACK MODE" -ForegroundColor Yellow
    Write-Host "===============================================================" -ForegroundColor Yellow
    
    $history = Get-VersionHistory
    
    if ($RollbackVersion) {
        $targetVersion = $RollbackVersion
    } elseif ($history.previous) {
        $targetVersion = $history.previous
    } else {
        Write-Error-Custom "No previous version found to rollback to"
        Write-Info "Available versions in history:"
        $history.history | ForEach-Object { Write-Info "  - $_" }
        exit 1
    }
    
    Write-Info "Rolling back to version: $targetVersion"
    Write-Info "Current version: $($history.current)"
    
    # Verify the target version exists in S3
    $versionExists = aws s3 ls "s3://$S3Bucket/versions/$targetVersion/" --region $AwsRegion 2>&1
    if ($LASTEXITCODE -ne 0) {
        Write-Error-Custom "Version $targetVersion not found in S3"
        exit 1
    }
    
    # Update the root to point to the rollback version
    Write-Info "Syncing rollback version to root..."
    aws s3 sync "s3://$S3Bucket/versions/$targetVersion" "s3://$S3Bucket" `
        --region $AwsRegion `
        --delete `
        --exclude "versions/*" `
        --quiet
    
    # Invalidate CloudFront
    Write-Info "Invalidating CloudFront cache..."
    $InvalidationResult = aws cloudfront create-invalidation `
        --distribution-id $CloudFrontDistributionId `
        --paths "/*" `
        --region $AwsRegion `
        --output json | ConvertFrom-Json
    
    # Update version history
    $history.previous = $history.current
    $history.current = $targetVersion
    Save-VersionHistory $history
    
    Write-Success "Rollback to $targetVersion completed!"
    Write-Info "Invalidation ID: $($InvalidationResult.Invalidation.Id)"
    exit 0
}

