# Step 3.5: Rebuild the doc-sync help SDK and copy it into public/help-sdk/
# so the React build picks up the freshest bundle. Skipped silently if the
# doc-sync repo isn't present (the React app still builds fine — TabsHelp
# falls back to "Couldn't load help" empty state).
Write-Step "3.5" "Building doc-sync help SDK..."
$DocSyncSdkDir = Join-Path $PSScriptRoot "..\doc-sync\sdk"
if (Test-Path $DocSyncSdkDir) {
    Push-Location $DocSyncSdkDir
    try {
        node build.js 2>&1 | Out-Null
        if ($LASTEXITCODE -ne 0) {
            Write-Warning-Custom "doc-sync SDK build failed (continuing)"
        } else {
            $sdkPublicDir = Join-Path $ClientDir "public\help-sdk"
            New-Item -ItemType Directory -Path $sdkPublicDir -Force | Out-Null
            Copy-Item "dist\tabs-help.min.js" $sdkPublicDir -Force
            Copy-Item "dist\tabs-help.js"     $sdkPublicDir -Force
            $minSize = [math]::Round((Get-Item (Join-Path $sdkPublicDir "tabs-help.min.js")).Length / 1KB, 1)
            Write-Success "Help SDK copied to public/help-sdk/ (min: $minSize KB)"
        }
    } finally { Pop-Location }
} else {
    Write-Info "doc-sync SDK source not present, using whatever's already in public/help-sdk/"
}

# Step 3.7: Verify the help API is reachable. Catches CORS / DNS / region
# misconfigurations BEFORE we ship a build that the SDK can't talk to.
# Both the help context and chat endpoints are checked. Pass `-SkipApiCheck`
# to bypass when you know the API is offline (rare).
Write-Step "3.7" "Health-checking help API..."
$HelpApiUrl = if ($env:REACT_APP_HELP_API_URL) { $env:REACT_APP_HELP_API_URL } else { "https://zsvzaeu172.execute-api.us-east-1.amazonaws.com/help/context" }
$HelpChatUrl = if ($env:REACT_APP_HELP_CHAT_URL) { $env:REACT_APP_HELP_CHAT_URL } else { "https://zsvzaeu172.execute-api.us-east-1.amazonaws.com/help/chat" }
$ProdOrigin = "https://keeptabs.app"

if ($SkipApiCheck) {
    Write-Warning-Custom "Skipped (-SkipApiCheck flag set)"
} else {
    # Probe context API with a known-bad route — should return 404 with proper CORS
    $contextProbe = curl.exe -s -o $null -w "%{http_code}" "$HelpApiUrl?route=__healthcheck__&role=public" -H "Origin: $ProdOrigin"
    if ($contextProbe -ne "404" -and $contextProbe -ne "200") {
        Write-Error-Custom "Help context API unreachable (HTTP $contextProbe at $HelpApiUrl)"
        Write-Info "   Set -SkipApiCheck to bypass, or check the API stack: doc-sync-api-prod"
        exit 1
    }
    Write-Success "Context API: HTTP $contextProbe (expected 404 or 200)"

    # Probe chat API with OPTIONS preflight — verifies the route exists and CORS is right
    $chatProbe = curl.exe -s -o $null -w "%{http_code}" -X OPTIONS $HelpChatUrl -H "Origin: $ProdOrigin" -H "Access-Control-Request-Method: POST" -H "Access-Control-Request-Headers: content-type"
    if ($chatProbe -ne "204" -and $chatProbe -ne "200") {
        Write-Error-Custom "Help chat API CORS preflight failed (HTTP $chatProbe at $HelpChatUrl)"
        exit 1
    }
    Write-Success "Chat API: OPTIONS $chatProbe"

    # Verify the production origin is in the API's CORS allow-list. The
    # OPTIONS response above only proves the URL is reachable — we also need
    # the actual ACAO header to come back with our origin echoed.
    $corsHeader = curl.exe -s -i -X OPTIONS $HelpApiUrl -H "Origin: $ProdOrigin" -H "Access-Control-Request-Method: GET" -H "Access-Control-Request-Headers: content-type" 2>&1 | Select-String "access-control-allow-origin: $([regex]::Escape($ProdOrigin))"
    if (-not $corsHeader) {
        Write-Error-Custom "Help API does not allow origin '$ProdOrigin'."
        Write-Info "   Add it to the AllowedOrigins parameter on the doc-sync-api-prod stack."
        exit 1
    }
    Write-Success "CORS allow-list contains $ProdOrigin"
}

# Step 4: Build for production
Write-Step 4 "Building for production (with code splitting)..."
$buildStart = Get-Date
npm run build 2>&1 | ForEach-Object {
    if ($_ -match "error|Error|ERROR") {
        Write-Host $_ -ForegroundColor Red
    } elseif ($_ -match "warning|Warning") {
        # Suppress warnings for cleaner output
    } elseif ($_ -match "File sizes|build\\static") {
        Write-Host $_ -ForegroundColor Gray
    }
}
if ($LASTEXITCODE -ne 0) {
    Write-Error-Custom "Build failed"
    exit 1
}
$buildTime = ((Get-Date) - $buildStart).TotalSeconds
Write-Success "Build completed in $([math]::Round($buildTime, 1))s"

# Verify build directory
