    Write-Error-Custom "Build directory not found"
    exit 1
}

# Show bundle analysis
Write-Info "Bundle Analysis:"
$jsFiles = Get-ChildItem "build/static/js/*.js" | Sort-Object Length -Descending | Select-Object -First 5
$jsFiles | ForEach-Object {
    $sizeKB = [math]::Round($_.Length / 1KB, 1)
    $color = if ($sizeKB -gt 500) { "Yellow" } elseif ($sizeKB -gt 200) { "Cyan" } else { "Green" }
    Write-Host "  $($_.Name): $sizeKB KB" -ForegroundColor $color
}
$totalSize = ($jsFiles | Measure-Object -Property Length -Sum).Sum / 1MB
Write-Info "Total JS (top 5): $([math]::Round($totalSize, 2)) MB"

# Step 5: Verify AWS credentials
Write-Step 5 "Verifying AWS credentials..."
$AwsIdentity = aws sts get-caller-identity --region $AwsRegion 2>&1 | ConvertFrom-Json
