    Write-Error-Custom "AWS credentials not configured"
    exit 1
}
Write-Success "AWS Account: $($AwsIdentity.Account)"

# Step 6: Upload new version to S3 (Blue-Green)
Write-Step 6 "Uploading new version to S3..."
$VersionPath = "versions/$AppVersion"
Write-Info "Deploying to: s3://$S3Bucket/$VersionPath"

# Upload to versioned folder first (the "green" deployment)
aws s3 sync build/ "s3://$S3Bucket/$VersionPath" `
    --region $AwsRegion `
    --cache-control "max-age=31536000,immutable" `
    --quiet

if ($LASTEXITCODE -ne 0) {
    Write-Error-Custom "Failed to upload to versioned folder"
    exit 1
}
Write-Success "Version $AppVersion uploaded to S3"

# Step 7: Atomic switch - sync to root (the "blue" becomes "green")
Write-Step 7 "Performing atomic switch to new version..."
Write-Info "Syncing new version to root (zero-downtime switch)..."

# Sync HTML files with no-cache (so they always get the latest)
aws s3 cp "build/index.html" "s3://$S3Bucket/index.html" `
    --region $AwsRegion `
    --cache-control "no-cache,no-store,must-revalidate" `
    --content-type "text/html" `
    --quiet

# Sync other root files
aws s3 sync build/ "s3://$S3Bucket" `
    --region $AwsRegion `
    --delete `
    --exclude "versions/*" `
    --exclude "*.html" `
    --cache-control "max-age=3600" `
    --quiet

# Sync static assets with long cache (they have content hashes)
aws s3 sync build/static "s3://$S3Bucket/static" `
    --region $AwsRegion `
    --cache-control "max-age=31536000,immutable" `
    --quiet

if ($LASTEXITCODE -ne 0) {
    Write-Error-Custom "Failed to sync to root"
    exit 1
}
Write-Success "Atomic switch completed"

# Step 8: Update version history
Write-Step 8 "Updating version history..."
$history = Get-VersionHistory
$history.previous = $history.current
$history.current = $AppVersion
$history.appVersion = $AppVersion
if (-not $history.history) { $history.history = @() }
$history.history = @($AppVersion) + $history.history | Select-Object -First 10
Save-VersionHistory $history
Write-Success "Version history updated"
Write-Info "Current: v$AppVersion"
Write-Info "Previous: v$($history.previous)"

# Step 9: Invalidate CloudFront cache
Write-Step 9 "Invalidating CloudFront cache..."
$InvalidationResult = aws cloudfront create-invalidation `
    --distribution-id $CloudFrontDistributionId `
    --paths "/index.html" "/*.html" "/static/*" `
    --region $AwsRegion `
    --output json | ConvertFrom-Json

$InvalidationId = $InvalidationResult.Invalidation.Id
Write-Success "Invalidation created: $InvalidationId"

# Step 10: Wait for invalidation (with timeout)
Write-Step 10 "Waiting for CloudFront propagation..."
$MaxWait = 120
$Elapsed = 0
$Interval = 5

while ($Elapsed -lt $MaxWait) {
    $Status = (aws cloudfront get-invalidation `
        --distribution-id $CloudFrontDistributionId `
        --id $InvalidationId `
        --region $AwsRegion `
        --output json | ConvertFrom-Json).Invalidation.Status
    
    if ($Status -eq "Completed") {
        Write-Success "CloudFront invalidation completed"
        break
    }
    
    Write-Host "." -NoNewline -ForegroundColor Gray
    Start-Sleep -Seconds $Interval
    $Elapsed += $Interval
}

if ($Elapsed -ge $MaxWait) {
    Write-Warning-Custom "Invalidation still in progress (continuing anyway)"
}
Write-Host ""

# Step 11: Verify deployment
Write-Step 11 "Verifying deployment..."
try {
    $Response = Invoke-WebRequest -Uri "https://keeptabs.app" -UseBasicParsing -TimeoutSec 10
    if ($Response.StatusCode -eq 200) {
        Write-Success "Website is live at https://keeptabs.app"
    }
} catch {
    Write-Warning-Custom "Could not verify: $_"
}

# Step 12: Cleanup old versions (keep last 5)
Write-Step 12 "Cleaning up old versions..."
