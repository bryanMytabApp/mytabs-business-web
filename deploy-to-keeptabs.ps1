$versionFolders = $allVersions | ForEach-Object { ($_ -split '\s+')[-1] -replace '/$', '' } | Where-Object { $_ -match '^\d{8}-\d{6}$' } | Sort-Object -Descending

if ($versionFolders.Count -gt 5) {
    $toDelete = $versionFolders | Select-Object -Skip 5
    foreach ($oldVersion in $toDelete) {
        Write-Info "Removing old version: $oldVersion"
        aws s3 rm "s3://$S3Bucket/versions/$oldVersion" --recursive --region $AwsRegion --quiet
    }
    Write-Success "Cleaned up $($toDelete.Count) old version(s)"
} else {
    Write-Info "No cleanup needed (keeping last 5 versions)"
}

